-- =====================================================================================
--  4. HÀM HELPER — hệ số mùa & phân bổ ngày
-- =====================================================================================
--  Hệ số mùa du lịch Việt Nam (nhân vào mức nền của tháng):
--    · Tết (tháng 1–2)          × 1.90  — cao điểm nghỉ lễ
--    · Tháng 3                  × 0.85
--    · Tháng 4–5                × 1.10
--    · Hè (tháng 6–8)          × 1.35
--    · Tháng 9                  × 0.95
--    · Tháng 10–11              × 1.15
--    · Cuối năm (tháng 12)      × 1.30
--    Bù trừ mùa thấp điểm tháng 2–3 (sau Tết) bằng hệ số tương đối.
CREATE OR REPLACE FUNCTION demo_season_factor(d date)
RETURNS numeric
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE EXTRACT(MONTH FROM d)::int
        WHEN 1  THEN 1.90   -- Tết Nguyên Đán
        WHEN 2  THEN 1.35   -- Tết / mùa lễ hội
        WHEN 3  THEN 0.62   -- thấp điểm sau Tết
        WHEN 4  THEN 1.10
        WHEN 5  THEN 1.05
        WHEN 6  THEN 1.30   -- bắt đầu mùa hè
        WHEN 7  THEN 1.45   -- cao điểm hè
        WHEN 8  THEN 1.40   -- cao điểm hè
        WHEN 9  THEN 0.95
        WHEN 10 THEN 1.15
        WHEN 11 THEN 1.15
        WHEN 12 THEN 1.30   -- cuối năm / kỷ niệm
        ELSE 1.00
    END
    * CASE
        WHEN EXTRACT(ISODOW FROM d)::int IN (6, 7) THEN 1.15   -- cuối tuần
        ELSE 1.00
      END;
$$;

COMMENT ON FUNCTION demo_season_factor(date) IS
    'Hệ số mùa du lịch cho ngày — dùng để phân bổ booking lịch sử tự nhiên.';

-- Hệ số theo năm: nền tảng non trẻ ⇒ lượng booking tăng dần qua các năm.
CREATE OR REPLACE FUNCTION demo_year_factor(d date)
RETURNS numeric
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE EXTRACT(YEAR FROM d)::int
        WHEN 2024 THEN 0.72
        WHEN 2025 THEN 0.92
        WHEN 2026 THEN 1.15
        ELSE 1.00
    END;
$$;

-- Chu kỳ tất toán 10 ngày: 1 = ngày 1–10, 2 = 11–20, 3 = 21–cuối tháng.
CREATE OR REPLACE FUNCTION demo_revenue_period(d date)
RETURNS text
LANGUAGE sql IMMUTABLE AS $$
    SELECT to_char(d, 'YYYY-MM') || '-' ||
           CASE WHEN EXTRACT(DAY FROM d)::int <= 10 THEN '1'
                WHEN EXTRACT(DAY FROM d)::int <= 20 THEN '2'
                ELSE '3' END;
$$;

COMMENT ON FUNCTION demo_revenue_period(date) IS
    'Kỳ doanh thu 10 ngày (yyyy-MM-D) — khớp SettlementPeriod của backend.';

-- Ngày trong tháng có "ngày lễ" để tăng biến động.
CREATE OR REPLACE FUNCTION demo_is_holiday(d date)
RETURNS boolean
LANGUAGE sql IMMUTABLE AS $$
    SELECT EXTRACT(MONTH FROM d)::int IN (1, 4, 5, 9, 12)   -- Tết, Giỗ, Hội, Trung thu, Tết dương
        OR EXTRACT(DAY FROM d)::int IN (1, 2, 3);            -- dịp lễ đầu tháng
$$;

-- Tổng số booking dự kiến cho một năm (mục tiêu ~21.000 cho 3 năm).
--  Bảng tra cứu đơn giản để script 12–14 cân đối tổng số theo năm.
CREATE OR REPLACE FUNCTION demo_year_booking_target(y integer)
RETURNS integer
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE y
        WHEN 2024 THEN 7800
        WHEN 2025 THEN 8400
        WHEN 2026 THEN 4800
        ELSE 0
    END;
$$;

