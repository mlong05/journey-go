-- =====================================================================================
--  1. BẢNG ĐIỀU KHIỂN (checkpoint)
-- =====================================================================================
--  Ghi trong CÙNG transaction với dữ liệu ⇒ script lỗi ⇒ mất cả data lẫn checkpoint
--  ⇒ chạy lại sẽ thử lại từ đầu, không để lại dữ liệu dở dang.
CREATE TABLE IF NOT EXISTS demo_seed_checkpoints (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    script_name     varchar(64)  NOT NULL UNIQUE,
    batch_tag       varchar(64)  NOT NULL,
    record_count    integer      NOT NULL DEFAULT 0,
    executed_at     timestamptz  NOT NULL DEFAULT now(),
    note            varchar(500)
);

COMMENT ON TABLE demo_seed_checkpoints IS
    'Checkpoint dữ liệu demo lịch sử JourneyGo — dùng để chống chạy trùng script seed.';

-- Bảng điều khiển thứ hai: đánh dấu bản ghi demo để quản lý / dọn dẹp riêng.
CREATE TABLE IF NOT EXISTS demo_seed_registry (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type     varchar(40)  NOT NULL,
    entity_id       bigint,
    batch_tag       varchar(64)  NOT NULL,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_demo_seed_registry UNIQUE (entity_type, entity_id, batch_tag)
);

COMMENT ON TABLE demo_seed_registry IS
    'Danh bạc bản ghi demo lịch sử — cho phép xác định & quản lý riêng dữ liệu demo.';

